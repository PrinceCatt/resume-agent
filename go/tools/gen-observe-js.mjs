// Regenerates go/app/observe.js from the in-page collect() in server/observe.ts, so the Go backend
// reads pages with exactly the same script. Run: node go/tools/gen-observe-js.mjs (Node 22.13+).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const src = fs.readFileSync(path.join(root, "server/observe.ts"), "utf8").replace(/\r\n/g, "\n");
const start = src.indexOf("function collect(");
const end = src.indexOf("\n}\n", start);
if (start < 0 || end < 0) throw new Error("collect() not found in server/observe.ts");
const js = stripTypeScriptTypes(src.slice(start, end + 2), { mode: "strip" });
const out = `// GENERATED by go/tools/gen-observe-js.mjs from server/observe.ts (collect). Do not edit by hand.\n(${js.trim()})\n`;
fs.writeFileSync(path.join(root, "go/app/observe.js"), out);
console.log("wrote go/app/observe.js", out.length, "chars");
